def create_dual_layer_pdf():
    c = canvas.Canvas(OUTPUT, pagesize=A4)
    page_width, page_height = A4

    for i, img_name in enumerate(IMAGE_FILES):
        img_path = os.path.join(WORK_DIR, img_name)
        if not os.path.exists(img_path):
            print(f"跳过不存在的文件: {img_name}")
            continue

        img = Image.open(img_path)
        img_w, img_h = img.size

        scale = min(page_width / img_w, page_height / img_h)
        draw_w = img_w * scale
        draw_h = img_h * scale
        x_offset = (page_width - draw_w) / 2
        y_offset = (page_height - draw_h) / 2

        c.drawImage(img_path, x_offset, y_offset, width=draw_w, height=draw_h,
                    preserveAspectRatio=True, anchor='c')

        if i < len(PAGE_TEXTS) and PAGE_TEXTS[i]:
            c.setFillAlpha(0)
            c.setFont("Helvetica", 1)
            lines = PAGE_TEXTS[i].strip().split('\n')
            text_y = page_height - 10
            for line in lines:
                if line.strip():
                    c.drawString(10, text_y, line.strip())
                    text_y -= 2
                    if text_y < 10:
                        break
            c.setFillAlpha(1)

        c.showPage()
        print(f"已处理: {img_name}")

    c.save()
    print(f"\n双层PDF已生成: {OUTPUT}")


if __name__ == "__main__":
    create_dual_layer_pdf()
